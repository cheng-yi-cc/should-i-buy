export function buildUserMessage(input: DecisionInput, answers: Answer[]): string {
  const lines: string[] = [
    `商品：${input.name}`,
    `价格：${input.price}元`,
    `用户描述：${input.description}`,
    '',
    '我的追问和你的回答：',
  ];

  answers.forEach((a, i) => {
    lines.push(`${i + 1}. ${a.question} → ${a.answer}`);
  });

  return lines.join('\n');
}
